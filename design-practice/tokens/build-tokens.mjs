import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dtcgDir = path.join(here, "dtcg");
const cssDir = path.join(here, "css");
const REF_RE = /^\{([^}]+)\}$/;

function isToken(value) {
  return value && typeof value === "object" && "$value" in value;
}

function isObject(value) {
  return value && typeof value === "object" && !Array.isArray(value);
}

function deepMerge(base, override) {
  const out = Array.isArray(base) ? [...base] : { ...base };
  for (const [key, value] of Object.entries(override)) {
    if (key.startsWith("$")) {
      out[key] = value;
      continue;
    }
    if (isObject(out[key]) && isObject(value) && !isToken(out[key]) && !isToken(value)) {
      out[key] = deepMerge(out[key], value);
    } else {
      out[key] = value;
    }
  }
  return out;
}

async function readJson(file) {
  const text = await readFile(path.join(dtcgDir, file), "utf8");
  return JSON.parse(text);
}

function getPath(root, tokenPath) {
  return tokenPath.split(".").reduce((node, part) => {
    if (!node || !(part in node)) return undefined;
    return node[part];
  }, root);
}

function collectTokens(node, prefix = [], out = new Map()) {
  if (!isObject(node)) return out;
  if (isToken(node)) {
    out.set(prefix.join("."), node);
    return out;
  }
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    collectTokens(value, [...prefix, key], out);
  }
  return out;
}

function resolveTokenValue(root, token, stack = []) {
  const raw = token.$value;
  if (typeof raw === "string") {
    const match = raw.match(REF_RE);
    if (match) {
      const refPath = match[1];
      if (stack.includes(refPath)) {
        throw new Error(`Circular token reference: ${[...stack, refPath].join(" -> ")}`);
      }
      const ref = getPath(root, refPath);
      if (!isToken(ref)) {
        throw new Error(`Unresolvable token reference: {${refPath}}`);
      }
      return resolveTokenValue(root, ref, [...stack, refPath]);
    }
  }
  return raw;
}

function toCssValue(type, value) {
  if (type === "cubicBezier") {
    if (!Array.isArray(value) || value.length !== 4) {
      throw new Error(`Invalid cubicBezier value: ${JSON.stringify(value)}`);
    }
    return `cubic-bezier(${value.join(", ")})`;
  }
  if (Array.isArray(value)) return value.join(", ");
  return String(value);
}

function cssName(tokenPath) {
  return `--${tokenPath.replace(/\./g, "-").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()}`;
}

function assertDtcg(root, label) {
  const tokens = collectTokens(root);
  const errors = [];
  for (const [tokenPath, token] of tokens.entries()) {
    if (!token.$type) errors.push(`${tokenPath} is missing $type`);
    try {
      resolveTokenValue(root, token, [tokenPath]);
    } catch (error) {
      errors.push(error.message);
    }
  }
  if (errors.length) {
    throw new Error(`${label} has invalid tokens:\n- ${errors.join("\n- ")}`);
  }
}

function renderCss(root, label) {
  assertDtcg(root, label);
  const tokens = [...collectTokens(root).entries()].sort(([a], [b]) => a.localeCompare(b));
  const lines = [
    "/* Generated by tokens/build-tokens.mjs. Do not edit by hand. */",
    `/* Source: DTCG base + semantic${label === "base" ? "" : ` + ${label}`} */`,
    ":root {"
  ];
  for (const [tokenPath, token] of tokens) {
    const value = resolveTokenValue(root, token, [tokenPath]);
    lines.push(`  ${cssName(tokenPath)}: ${toCssValue(token.$type, value)};`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

function directionName(file) {
  return file.replace(/^theme-/, "").replace(/\.json$/, "");
}

async function main() {
  const base = await readJson("base.json");
  const semantic = await readJson("semantic.json");
  const baseSemantic = deepMerge(base, semantic);

  await mkdir(cssDir, { recursive: true });
  await writeFile(path.join(cssDir, "base.css"), renderCss(baseSemantic, "base"));

  const themeFiles = (await readdir(dtcgDir))
    .filter((file) => /^theme-.+\.json$/.test(file))
    .sort();

  for (const themeFile of themeFiles) {
    const theme = await readJson(themeFile);
    const direction = directionName(themeFile);
    const themed = deepMerge(baseSemantic, theme);
    await writeFile(path.join(cssDir, `${direction}.css`), renderCss(themed, themeFile));
  }

  console.log(`Generated ${themeFiles.length + 1} CSS files in ${path.relative(process.cwd(), cssDir)}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
